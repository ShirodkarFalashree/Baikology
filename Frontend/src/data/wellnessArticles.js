/**
 * Filter or prioritize articles based on detected topic keywords
 */
export function getTunedArticles(tunedTopics = []) {
  if (!Array.isArray(tunedTopics) || tunedTopics.length === 0) {
    return WELLNESS_ARTICLES;
  }

  const topicSet = new Set(tunedTopics.map((t) => t.toLowerCase()));

  // Prioritize articles matching the topics
  const matching = WELLNESS_ARTICLES.filter((a) =>
    topicSet.has(a.category.toLowerCase()) ||
    a.tags.some((tag) => topicSet.has(tag.toLowerCase()))
  );

  const nonMatching = WELLNESS_ARTICLES.filter(
    (a) => !matching.some((m) => m.id === a.id)
  );

  return [...matching, ...nonMatching];
}

